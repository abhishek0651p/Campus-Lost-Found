  // ---- Scroll Reveal (IntersectionObserver) --------------------------------
  function initScrollReveal() {
    const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    if (prefersReduced) {
      // If user prefers reduced motion, just show everything immediately
      $$('.reveal').forEach(el => el.classList.add('visible'));
      return;
    }

    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        if (entry.isIntersecting) {
          entry.target.classList.add('visible');
          observer.unobserve(entry.target);
        }
      });
    }, {
      threshold: 0.15,
      rootMargin: '0px 0px -40px 0px'
    });

    $$('.reveal').forEach(el => observer.observe(el));
  }

  // ---- Scroll-Driven Animations (rAF cinematic engine) --------------------
  function initScrollDrivenAnimations() {
    const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    if (prefersReduced) {
      // Show everything immediately, no scroll animations
      $$('.float-card').forEach(c => { c.style.opacity = '1'; });
      $$('.step-card').forEach(c => { c.style.opacity = '1'; c.style.transform = 'none'; });
      $$('.matching-item-card').forEach(c => { c.style.opacity = '1'; c.style.transform = 'none'; });
      $$('.criteria-item').forEach(c => { c.style.opacity = '1'; c.style.transform = 'none'; });
      $$('.example-card').forEach(c => { c.style.opacity = '1'; c.style.transform = 'none'; });
      $$('.stat-landing-card').forEach(c => { c.style.opacity = '1'; c.style.transform = 'none'; });
      const ctaFinal = $('.cta-final');
      if (ctaFinal) { ctaFinal.style.opacity = '1'; ctaFinal.style.transform = 'none'; }
      return;
    }

    // --- Cache DOM elements ---
    const heroSection     = $('#hero');
    const heroTitle       = $('.hero-title');
    const heroBadge       = $('.hero-badge');
    const heroTagline     = $('.hero-tagline');
    const heroCtas        = $('.hero-ctas');
    const heroScrollHint  = $('.hero-scroll-hint');
    const heroGrid        = heroSection ? heroSection.querySelector('.hero-section::before') : null;
    const floatCards      = $$('.float-card');
    const floatSpeeds     = [0.55, 0.40, 0.25, 0.45, 0.20]; // different parallax per card
    const floatRotations  = [2, -1.5, 1, -2, 1.5];

    const howSection      = $('#how-it-works');
    const stepCards       = $$('.step-card');
    const stepsGridEl     = $('.steps-grid');

    const matchSection    = $('#matching-engine');
    const lostCard        = $('.matching-item-card--lost');
    const foundCard       = $('.matching-item-card--found');
    const matchConnector  = $('.matching-connector');
    const criteriaItems   = $$('.criteria-item');
    const scoreFill       = $('#landingScoreFill');
    const scoreNumber     = $('#landingScoreNumber');
    const scoreRingEl     = $('#landingScoreRing');
    const scoreDisplay    = $('.score-display');
    const scoreEngineLabel = $('.score-engine-label');
    const circumference   = 2 * Math.PI * 70;

    // Get real top match score from loaded data
    const topMatchScore = appData.matches.length > 0
      ? Math.max(...appData.matches.map(m => m.score))
      : 86;

    const examplesSection = $('#examples');
    const exampleCards    = $$('.example-card');

    const statsSection    = $('#stats-cta');
    const statCards       = $$('.stat-landing-card');
    const ctaFinal        = $('.cta-final');

    // --- Tracking state ---
    let statsAnimated = false;
    let scoreGlowApplied = false;
    let lastScrollY = -1;

    // --- Easing helpers ---
    function clamp(val, min, max) { return Math.min(Math.max(val, min), max); }
    function easeOutCubic(t) { return 1 - Math.pow(1 - t, 3); }
    function easeInOutCubic(t) { return t < 0.5 ? 4*t*t*t : 1 - Math.pow(-2*t+2, 3)/2; }

    // Calculate how far a section has been scrolled into view
    function getSectionProgress(section) {
      if (!section) return 0;
      const rect = section.getBoundingClientRect();
      const vh = window.innerHeight;
      
      // Failsafe: If scrolled to the absolute bottom of the page, force 100% progress
      if (window.scrollY + vh >= document.documentElement.scrollHeight - 10) {
        return 1;
      }
      
      // Progress from 0 (section enters bottom) to 1 (section reaches 20% from top of viewport)
      // This guarantees animations complete while the section is still highly visible.
      const raw = (vh - rect.top) / (vh * 0.8);
      return clamp(raw, 0, 1);
    }

    function updateAnimations() {
      const scrollY = window.scrollY;
      if (scrollY === lastScrollY) {
        requestAnimationFrame(updateAnimations);
        return;
      }
      lastScrollY = scrollY;

      // ========== HERO SECTION ==========
      if (heroSection) {
        const heroH = heroSection.offsetHeight;
        const heroProgress = clamp(scrollY / heroH, 0, 1.5);
        const ep = easeOutCubic(clamp(heroProgress, 0, 1));

        // Title: scale up slightly and translate down as user scrolls past
        if (heroTitle) {
          const scale = 1 + heroProgress * 0.08;
          const translateY = heroProgress * 100;
          const opacity = 1 - clamp(heroProgress * 1.2, 0, 1);
          heroTitle.style.transform = `scale(${scale}) translateY(${translateY}px)`;
          heroTitle.style.opacity = opacity;
        }

        // Badge, tagline, CTAs fade out with parallax
        if (heroBadge) {
          heroBadge.style.transform = `translateY(${heroProgress * 50}px)`;
          heroBadge.style.opacity = 1 - clamp(heroProgress * 1.5, 0, 1);
        }
        if (heroTagline) {
          heroTagline.style.transform = `translateY(${heroProgress * 80}px)`;
          heroTagline.style.opacity = 1 - clamp(heroProgress * 1.3, 0, 1);
        }
        if (heroCtas) {
          heroCtas.style.transform = `translateY(${heroProgress * 90}px)`;
          heroCtas.style.opacity = 1 - clamp(heroProgress * 1.4, 0, 1);
        }

        // Scroll hint fades out quickly
        if (heroScrollHint) {
          heroScrollHint.style.opacity = 1 - clamp(heroProgress * 3, 0, 1);
        }

        // Float cards — parallax with depth rotation
        floatCards.forEach((card, i) => {
          const speed = floatSpeeds[i] || 0.2;
          const rot = floatRotations[i] || 0;
          const y = scrollY * speed;
          const rotate = heroProgress * rot;
          const scale = 1 + heroProgress * 0.02;
          card.style.transform = `translateY(-${y}px) rotate(${rotate}deg) scale(${scale})`;
        });

        // Background grid parallax (via CSS custom property on hero section)
        heroSection.style.setProperty('--grid-offset', `${scrollY * 0.08}px`);
      }

      // ========== HOW IT WORKS ==========
      if (howSection) {
        const howProg = getSectionProgress(howSection);

        // Step cards: sequential reveal based on scroll progress
        stepCards.forEach((card, i) => {
          // Each card activates at a different threshold
          const threshold = 0.1 + i * 0.15;
          const cardProgress = clamp((howProg - threshold) / 0.15, 0, 1);
          const ep = easeOutCubic(cardProgress);

          const translateY = (1 - ep) * 90;
          const translateX = (1 - ep) * (i % 2 === 0 ? -20 : 20);
          const rotateY = (1 - ep) * (i % 2 === 0 ? -12 : 12);
          const scale = 0.85 + ep * 0.15;

          card.style.transform = `translateY(${translateY}px) translateX(${translateX}px) rotateY(${rotateY}deg) scale(${scale})`;


          // Add 'active' class when fully revealed for border highlight
          card.classList.toggle('scroll-active', cardProgress > 0.8);
        });

        // Connecting line progressive draw
        if (stepsGridEl) {
          const lineProg = clamp((howProg - 0.1) / 0.5, 0, 1);
          stepsGridEl.style.setProperty('--line-progress', easeInOutCubic(lineProg));
        }
      }

      // ========== C++ MATCHING ENGINE (strongest section) ==========
      if (matchSection) {
        const matchProg = getSectionProgress(matchSection);

        // Phase 1: Cards slide in (0.1 → 0.35)
        const cardSlideProgress = clamp((matchProg - 0.1) / 0.25, 0, 1);
        const cardEased = easeOutCubic(cardSlideProgress);

        if (lostCard) {
          const translateX = (1 - cardEased) * -180;
          const rotateY = (1 - cardEased) * -12;
          lostCard.style.transform = `translateX(${translateX}px) rotateY(${rotateY}deg)`;

        }

        if (foundCard) {
          const translateX = (1 - cardEased) * 180;
          const rotateY = (1 - cardEased) * 12;
          foundCard.style.transform = `translateX(${translateX}px) rotateY(${rotateY}deg)`;

        }

        // Connector draws in between cards
        if (matchConnector) {
          const connProg = clamp((matchProg - 0.25) / 0.15, 0, 1);
          const connEased = easeOutCubic(connProg);

          matchConnector.style.transform = `scaleY(${connEased}) scaleX(${0.5 + 0.5 * connEased})`;
        }

        // Phase 2: Criteria appear sequentially (0.3 → 0.6)
        criteriaItems.forEach((item, i) => {
          const criteriaStart = 0.25 + i * 0.055;
          const critProg = clamp((matchProg - criteriaStart) / 0.08, 0, 1);
          const critEased = easeOutCubic(critProg);

          const translateY = (1 - critEased) * 60;
          const scale = 0.85 + critEased * 0.15;

          item.style.transform = `translateY(${translateY}px) scale(${scale})`;


          // Weight bar animation — add progress attribute
          item.style.setProperty('--weight-progress', critEased);
          item.classList.toggle('scroll-active', critProg > 0.5);
        });

        // Phase 3: Score ring animates (0.45 → 0.7)
        const scoreProg = clamp((matchProg - 0.45) / 0.25, 0, 1);
        const scoreEased = easeInOutCubic(scoreProg);

        if (scoreFill) {
          const currentScore = Math.round(scoreEased * topMatchScore);
          const offset = circumference - (currentScore / 100) * circumference;
          scoreFill.style.strokeDashoffset = offset;
          scoreFill.style.transition = 'none'; // JS drives it, no CSS transition
        }

        if (scoreNumber) {
          const currentScore = Math.round(scoreEased * topMatchScore);
          scoreNumber.textContent = currentScore + '%';
        }

        // Score display fade in
        if (scoreDisplay) {
          const sdProg = clamp((matchProg - 0.4) / 0.15, 0, 1);

          scoreDisplay.style.transform = `scale(${0.75 + easeOutCubic(sdProg) * 0.25})`;
        }

        // Engine label fade in
        if (scoreEngineLabel) {
          const elProg = clamp((matchProg - 0.55) / 0.1, 0, 1);

        }

        // Glow pulse when score completes
        if (scoreProg >= 0.95 && !scoreGlowApplied && scoreRingEl) {
          scoreGlowApplied = true;
          scoreRingEl.classList.add('score-glow-pulse');
        }
      }

      // ========== MATCH EXAMPLES ==========
      if (examplesSection) {
        const exProg = getSectionProgress(examplesSection);

        exampleCards.forEach((card, i) => {
          const threshold = 0.1 + i * 0.15;
          const cardProg = clamp((exProg - threshold) / 0.15, 0, 1);
          const ep = easeOutCubic(cardProg);

          // Slide up and slightly from the side, with stacking depth
          const translateY = (1 - ep) * 80;
          const translateX = (1 - ep) * (i * 15 - 15);
          const scale = 0.88 + ep * 0.12;
          const rotateZ = (1 - ep) * (i - 1) * 3;

          card.style.transform = `translateY(${translateY}px) translateX(${translateX}px) scale(${scale}) rotate(${rotateZ}deg)`;

        });
      }

      // ========== CAMPUS IMPACT / STATS ==========
      if (statsSection) {
        const statProg = getSectionProgress(statsSection);

        // Stat cards: parallax scale and stagger
        statCards.forEach((card, i) => {
          const threshold = 0.1 + i * 0.1;
          const cardProg = clamp((statProg - threshold) / 0.15, 0, 1);
          const ep = easeOutCubic(cardProg);

          const translateY = (1 - ep) * 70;
          const scale = 0.85 + ep * 0.15;

          card.style.transform = `translateY(${translateY}px) scale(${scale})`;

        });

        // Trigger counter animation once cards are visible
        if (statProg > 0.25 && !statsAnimated) {
          statsAnimated = true;
          const lost = appData.lost_items.length;
          const found = appData.found_items.length;
          const matches = appData.matches.length;
          const total = lost + found;
          const rate = total > 0 ? Math.min(Math.round((matches / total) * 100), 100) : 0;
          animateCounter('landingStatLost', lost);
          animateCounter('landingStatFound', found);
          animateCounter('landingStatMatches', matches);
          animateCounter('landingStatRate', rate, '%');
        }

        // CTA final fade in
        if (ctaFinal) {
          const ctaProg = clamp((statProg - 0.4) / 0.2, 0, 1);
          const ep = easeOutCubic(ctaProg);
          ctaFinal.style.transform = `translateY(${(1 - ep) * 70}px) scale(${0.95 + ep * 0.05})`;

        }
      }

      requestAnimationFrame(updateAnimations);
    }

    // --- Set initial styles & strip conflicting CSS transitions ---
    // The .reveal class has CSS transitions that fight our rAF loop. We must remove it
    // from elements we control dynamically.
    
    // Float cards are already opacity:0 via CSS
    // Remove CSS transform transitions to stop fighting our rAF loop
    stepCards.forEach(card => { 
      card.classList.remove('reveal');
      card.style.transition = 'border-color 250ms, box-shadow 250ms';
      card.style.transform = 'translateY(60px)'; 
    });
    if (lostCard) { 
      lostCard.classList.remove('reveal');
      lostCard.style.transition = 'none';
      lostCard.style.transform = 'translateX(-120px)'; 
    }
    if (foundCard) { 
      foundCard.classList.remove('reveal');
      foundCard.style.transition = 'none';
      foundCard.style.transform = 'translateX(120px)'; 
    }
    if (matchConnector) { 
      matchConnector.style.transition = 'none';
      matchConnector.style.transform = 'scaleY(0)'; 
    }
    criteriaItems.forEach(item => { 
      item.classList.remove('reveal');
      item.style.transition = 'border-color 250ms, box-shadow 250ms';
      item.style.transform = 'translateY(30px) scale(0.85)'; 
    });
    if (scoreDisplay) { 
      scoreDisplay.classList.remove('reveal');
      scoreDisplay.style.transition = 'none';
      scoreDisplay.style.transform = 'scale(0.9)'; 
    }
    if (scoreEngineLabel) { 
      scoreEngineLabel.classList.remove('reveal');
    }
    // Example cards
    exampleCards.forEach(card => { 
      card.classList.remove('reveal');
      card.style.transition = 'box-shadow 250ms';
      card.style.transform = 'translateY(50px)'; 
    });
    // Stat cards
    statCards.forEach(card => { 
      card.classList.remove('reveal');
      card.style.transition = 'box-shadow 250ms';
      card.style.transform = 'translateY(40px) scale(0.9)'; 
    });
    if (ctaFinal) { 
      ctaFinal.classList.remove('reveal');
      ctaFinal.style.transition = 'none';
      ctaFinal.style.transform = 'translateY(30px)'; 
    }

    // --- Start the animation loop ---
    requestAnimationFrame(updateAnimations);
  }

  // ---- Landing Nav Scroll Effect -------------------------------------------
