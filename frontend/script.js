  function buildMatchAnalysis(match, lost, found) {
    // Criterion weights (matching C++ engine)
    const weights = {
      category: 25,
      color: 10,
      brand: 10,
      location_proximity: 20,
      date_proximity: 10,
      description_keywords: 15,
      tags_overlap: 10
    };

    // Calculate per-criterion scores based on what was matched
    const matchedOn = match.matched_on || [];
    const criteria = [
      { key: 'category', label: 'Category', icon: '📂', weight: weights.category },
      { key: 'color', label: 'Color', icon: '🎨', weight: weights.color },
      { key: 'brand', label: 'Brand', icon: '🏷️', weight: weights.brand },
      { key: 'location_proximity', label: 'Location', icon: '📍', weight: weights.location_proximity },
      { key: 'date_proximity', label: 'Date Proximity', icon: '📅', weight: weights.date_proximity },
      { key: 'description_keywords', label: 'Description', icon: '📝', weight: weights.description_keywords },
      { key: 'tags_overlap', label: 'Tags', icon: '🔖', weight: weights.tags_overlap }
    ];

    const criteriaDetails = criteria.map(c => {
      const isMatched = matchedOn.includes(c.key);
      let score = isMatched ? c.weight : 0;
      let lostVal = getItemValue(lost, c.key);
      let foundVal = getItemValue(found, c.key);

      // For partial matches, we can show the actual values even if not fully matched
      // The C++ engine gives full weight when criterion is in matched_on
      return {
        ...c,
        isMatched,
        score,
        lostVal: lostVal || '—',
        foundVal: foundVal || '—',
        maxScore: c.weight
      };
    });

    // Generate "Why this matched" reasons from actual data
    const reasons = generateMatchReasons(match, lost, found);

    return {
      match,
      lost,
      found,
      criteria: criteriaDetails,
      reasons,
      totalScore: match.score
    };
  }

  function getItemValue(item, criterion) {
    switch (criterion) {
      case 'category': return item.category;
      case 'color': return item.color;
      case 'brand': return item.brand || '—';
      case 'location_proximity': return item.location;
      case 'date_proximity': return item.date;
      case 'description_keywords': return item.description ? item.description.substring(0, 80) + '…' : '—';
      case 'tags_overlap': return (item.tags || []).slice(0, 5).join(', ');
      default: return '—';
    }
  }

  function generateMatchReasons(match, lost, found) {
    const reasons = [];
    const matchedOn = match.matched_on || [];

    // Check each criterion and generate human-readable reason
    if (matchedOn.includes('category')) {
      reasons.push({
        icon: '✓',
        text: `Same category: <strong>${escHTML(lost.category)}</strong>`
      });
    }

    if (matchedOn.includes('color') && lost.color && found.color) {
      const colorMatch = lost.color.toLowerCase() === found.color.toLowerCase();
      if (colorMatch) {
        reasons.push({
          icon: '✓',
          text: `Same color: <strong>${escHTML(lost.color)}</strong>`
        });
      } else {
        reasons.push({
          icon: '✓',
          text: `Similar color: <strong>${escHTML(lost.color)}</strong> ↔ <strong>${escHTML(found.color)}</strong>`
        });
      }
    }

    if (matchedOn.includes('brand') && lost.brand && found.brand) {
      const brandMatch = lost.brand.toLowerCase() === found.brand.toLowerCase();
      if (brandMatch) {
        reasons.push({
          icon: '✓',
          text: `Same brand: <strong>${escHTML(lost.brand)}</strong>`
        });
      } else {
        reasons.push({
          icon: '✓',
          text: `Related brands: <strong>${escHTML(lost.brand)}</strong> ↔ <strong>${escHTML(found.brand)}</strong>`
        });
      }
    }

    if (matchedOn.includes('location_proximity') || matchedOn.includes('location_exact')) {
      reasons.push({
        icon: '✓',
        text: `Similar location: <strong>${escHTML(lost.location)}</strong> ↔ <strong>${escHTML(found.location)}</strong>`
      });
    }

    if (matchedOn.includes('date_proximity')) {
      const lostDate = new Date(lost.date + 'T00:00:00');
      const foundDate = new Date(found.date + 'T00:00:00');
      const diffDays = Math.abs(Math.round((foundDate - lostDate) / (1000 * 60 * 60 * 24)));
      reasons.push({
        icon: '✓',
        text: `Close report dates: ${diffDays} day${diffDays !== 1 ? 's' : ''} apart`
      });
    }

    if (matchedOn.includes('description_keywords')) {
      reasons.push({
        icon: '✓',
        text: `Matching keywords in descriptions`
      });
    }

    if (matchedOn.includes('tags_overlap')) {
      const lostTags = lost.tags || [];
      const foundTags = found.tags || [];
      const commonTags = lostTags.filter(t => foundTags.some(ft => ft.toLowerCase() === t.toLowerCase()));
      if (commonTags.length > 0) {
        reasons.push({
          icon: '✓',
          text: `Shared tags: <strong>${commonTags.slice(0, 3).map(escHTML).join(', ')}</strong>${commonTags.length > 3 ? '…' : ''}`
        });
      } else {
        reasons.push({
          icon: '✓',
          text: `Tag overlap detected`
        });
      }
    }

    return reasons;
  }

