  async function startDirections(blockId) {
    const loc = CAMPUS_LOCATIONS[blockId];
    if (!loc) return;
    
    const btn = $('#startDirectionsBtn');
    btn.textContent = 'Locating...';
    btn.disabled = true;
    
    if (!navigator.geolocation) {
      showToast('Geolocation is not supported by your browser.', 'error');
      btn.textContent = 'Start Directions';
      btn.disabled = false;
      return;
    }
    
    navigator.geolocation.getCurrentPosition(
      async (pos) => {
        const userLat = pos.coords.latitude;
        const userLng = pos.coords.longitude;
        
        // Add user marker
        const userIcon = L.divIcon({
          className: 'custom-div-icon',
          html: `<div style="background-color:#3b82f6;width:14px;height:14px;border-radius:50%;border:2px solid white;box-shadow:0 0 4px rgba(0,0,0,0.5);"></div>`,
          iconSize: [18, 18],
          iconAnchor: [9, 9]
        });
        
        if (userMarker) campusMapInstance.removeLayer(userMarker);
        userMarker = L.marker([userLat, userLng], {icon: userIcon}).addTo(campusMapInstance)
          .bindPopup('You are here').openPopup();
          
        // Fit bounds to show both user and destination
        const bounds = L.latLngBounds([userLat, userLng], [loc.lat, loc.lng]);
        campusMapInstance.fitBounds(bounds, { padding: [50, 50] });
        
        // Fetch OSRM routing data
        try {
          btn.textContent = 'Calculating route...';
          const res = await fetch(`https://router.project-osrm.org/route/v1/foot/${userLng},${userLat};${loc.lng},${loc.lat}?overview=full&geometries=geojson`);
          const data = await res.json();
          
          if (data.code === 'Ok' && data.routes.length > 0) {
            const route = data.routes[0];
            const coords = route.geometry.coordinates.map(c => [c[1], c[0]]); // Swap lng,lat to lat,lng
            
            L.polyline(coords, { color: '#3b82f6', weight: 4, opacity: 0.8, dashArray: '8, 8' }).addTo(campusMapInstance);
            
            let dist = route.distance;
            let distStr = dist > 1000 ? (dist / 1000).toFixed(1) + ' km' : Math.round(dist) + ' m';
            let duration = Math.round(route.duration / 60);
            let timeStr = duration > 0 ? duration + ' min' : '< 1 min';
            
            $('#mapDistance').textContent = distStr;
            $('#mapDuration').textContent = timeStr;
            $('#mapRouteInfo').style.display = 'block';
            btn.style.display = 'none'; // Hide button once route is active
          } else {
            showToast('Could not calculate a walking route.', 'warning');
            btn.textContent = 'Start Directions';
            btn.disabled = false;
          }
        } catch(err) {
          console.error(err);
          showToast('Failed to fetch route. Check connection.', 'error');
          btn.textContent = 'Start Directions';
          btn.disabled = false;
        }
      },
      (err) => {
        showToast('Location permission denied or unavailable.', 'error');
        btn.textContent = 'Start Directions';
        btn.disabled = false;
      },
      { enableHighAccuracy: true, timeout: 10000 }
    );
  }


