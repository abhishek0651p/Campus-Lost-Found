  function animateMatchAnalysis(analysis) {
    const { criteria, totalScore } = analysis;

    // Animate main score ring
    const circumference = 2 * Math.PI * 38;
    const scoreFill = $('#analysisScoreFill');
    const scoreNumber = $('#analysisScoreNumber');

    if (scoreFill && scoreNumber) {
      const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
      if (prefersReduced) {
        const offset = circumference - (totalScore / 100) * circumference;
        scoreFill.style.strokeDashoffset = offset;
        scoreNumber.textContent = totalScore + '%';
      } else {
        animateScoreRing(scoreFill, scoreNumber, circumference, totalScore, 1200);
      }
    }

    // Animate criteria progress bars and scores
    criteria.forEach((c, i) => {
      const fill = $(`#criterionFill-${c.key}`);
      const scoreEl = $(`#criterionScore-${c.key}`);

      if (fill && scoreEl) {
        const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        const delay = 300 + i * 100;

        if (prefersReduced) {
          fill.style.width = c.score + '%';
          scoreEl.textContent = c.score + '%';
        } else {
          setTimeout(() => {
            animateCriterion(fill, scoreEl, c.score);
          }, delay);
        }
      }
    });
  }

  function animateScoreRing(fillEl, numberEl, circumference, targetScore, duration) {
    const start = performance.now();

    function step(now) {
      const elapsed = now - start;
      const progress = Math.min(elapsed / duration, 1);
      const eased = 1 - Math.pow(1 - progress, 3); // easeOutCubic
      const currentScore = Math.round(eased * targetScore);
      const offset = circumference - (currentScore / 100) * circumference;

      fillEl.style.strokeDashoffset = offset;
      numberEl.textContent = currentScore + '%';

      if (progress < 1) {
        requestAnimationFrame(step);
      }
    }

    requestAnimationFrame(step);
  }

  function animateCriterion(fillEl, scoreEl, targetScore) {
    const duration = 800;
    const start = performance.now();

    function step(now) {
      const elapsed = now - start;
      const progress = Math.min(elapsed / duration, 1);
      const eased = 1 - Math.pow(1 - progress, 3);
      const currentScore = Math.round(eased * targetScore);

      fillEl.style.width = currentScore + '%';
      scoreEl.textContent = currentScore + '%';

      if (progress < 1) {
        requestAnimationFrame(step);
      }
    }

    requestAnimationFrame(step);
  }

  // ---- Match Actions -------------------------------------------------------
  async function handleMatchAction(action, matchId) {
    const match = appData.matches.find(m => m.id === matchId);
    if (!match) return;

    const previousStatus = match.status;
    const newStatus = action === 'confirm' ? 'confirmed' : action === 'reject' ? 'rejected' : 'pending';

    // Optimistic UI update
    match.status = newStatus;
    if (currentSection === 'dashboard') renderDashboard();
    if (currentSection === 'matches') renderAllMatches(activeFilters.matches);
    initIcons();

    // Persist to server
    try {
      const res = await fetch('/api/update-match', {
        method: 'POST',
        headers: adminHeaders(),
        body: JSON.stringify({ match_id: matchId, status: newStatus })
      });

      const data = await res.json();

      if (!res.ok || !data.success) {
        // Revert on failure
        match.status = previousStatus;
        if (currentSection === 'dashboard') renderDashboard();
        if (currentSection === 'matches') renderAllMatches(activeFilters.matches);
        initIcons();
        showToast(data.error || 'Failed to update match.', 'error');
        return;
      }

      showToast(
        action === 'confirm'
          ? 'Match confirmed and saved! Both parties will be notified.'
          : action === 'reject'
          ? 'Match rejected and saved.'
          : 'Match reset to pending.',
        action === 'confirm' ? 'success' : 'info'
      );

      if (action === 'confirm') {
        showSimulatedEmail(matchId);
      }

    } catch (err) {
      // Revert on network error
      match.status = previousStatus;
      if (currentSection === 'dashboard') renderDashboard();
      if (currentSection === 'matches') renderAllMatches(activeFilters.matches);
      initIcons();
      console.error('Failed to update match:', err);
      showToast('Network error — could not save match status. Is server.py running?', 'error');
    }
  }

