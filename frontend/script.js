  async function submitReport() {
    const title = $('#itemTitle').value.trim();
    const category = $('#itemCategory').value;
    const description = $('#itemDescription').value.trim();
    const location = $('#itemLocation').value.trim();
    const name = $('#reporterName').value.trim();
    const email = $('#reporterEmail').value.trim();

    if (!title || !category || !description || !location || !name || !email) {
      showToast('Please fill in all required fields.', 'error');
      return;
    }

    const tagsRaw = $('#itemTags').value.trim();
    const tags = tagsRaw ? tagsRaw.split(',').map(t => t.trim()).filter(Boolean) : [];

    const block = $('#itemBlock').value;
    const buildingName = block ? $('#itemBlock').options[$('#itemBlock').selectedIndex].text : '';
    const floor = $('#itemFloor').value;
    const room = $('#itemRoom').value.trim();

    const payload = {
      type: reportType,
      title,
      category,
      description,
      location,
      block,
      building: buildingName,
      floor,
      room,
      date: $('#itemDate').value || new Date().toISOString().split('T')[0],
      time: $('#itemTime').value || new Date().toTimeString().slice(0, 5),
      reporter: name,
      email,
      color: $('#itemColor').value.trim(),
      brand: $('#itemBrand').value.trim(),
      tags: tagsRaw,
      imageUrl: $('#itemImageUrl').value.trim()
    };

    // Validate imageUrl before sending — reject javascript: and data: URIs
    // (mirror of the server-side check in server.py _handle_add_item).
    if (payload.imageUrl) {
      const scheme = String(payload.imageUrl).split(':')[0].toLowerCase();
      if (scheme === 'javascript' || scheme === 'data' || scheme === 'vbscript') {
        showToast('Invalid image URL: javascript:, data:, and vbscript: URIs are not permitted.', 'error');
        return;
      }
    }

    // Disable submit button while saving
    const submitBtn = $('#submitReportBtn');
    const originalText = submitBtn.textContent;
    submitBtn.textContent = 'Saving...';
    submitBtn.disabled = true;

    try {
      const res = await fetch('/api/add-item', {
        method: 'POST',
        headers: adminHeaders(),
        body: JSON.stringify(payload)
      });

      const data = await res.json();

      if (!res.ok || !data.success) {
        showToast(data.error || 'Failed to save item.', 'error');
        return;
      }

      // Close modal and reload data from disk
      const submittedType = reportType;
      closeModal();
      await loadData();

      // Refresh dashboard
      if (!isLandingVisible) {
        renderDashboard();
        navigateTo(currentSection);
      }

      // Update landing stats if visible
      populateLandingStats();

      showToast(
        `${submittedType === 'lost' ? 'Lost' : 'Found'} item "${title}" saved to items.json!`,
        'success'
      );
    } catch (err) {
      console.error('Failed to save item:', err);
      showToast('Network error — could not save item. Is server.py running?', 'error');
    } finally {
      submitBtn.textContent = originalText;
      submitBtn.disabled = false;
    }
  }

